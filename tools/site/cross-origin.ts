// The site's cross-origin policy: closed by default, open only for the files
// other sites are meant to show.
//
// Every response carries SECURITY_HEADERS (worker.ts and the `/*` block of
// src/_headers), which say `Cross-Origin-Resource-Policy: same-origin` and
// never send `Access-Control-Allow-Origin`, so another site can neither embed
// our files nor read them from script. The favicons and the Open Graph image
// are the exceptions: search engines, browsers' tab strips, link previews and
// favicon services show them on other origins. build.ts appends the rules in
// openAssetHeaders() to dist/_headers, so this list is the only place a file
// is opened. See "Cross-origin policy" in README.md.

/**
 * Paths on bookclerk.app that any origin may embed and read: the icons the
 * page head and the web manifest declare, and the `og:image`. build.test.ts
 * checks this list matches what the pages declare, so a new icon is either
 * added here or stays closed.
 */
export const OPEN_ASSETS: readonly string[] = [
  "/favicon.ico",
  "/favicon.svg",
  "/favicon-16x16.png",
  "/favicon-32x32.png",
  "/favicon-96x96.png",
  "/apple-touch-icon.png",
  "/android-chrome-192x192.png",
  "/android-chrome-512x512.png",
  "/social-card.png",
];

/**
 * Headers an open asset gets on top of SECURITY_HEADERS. They carry no
 * cookies or private data, so `*` without credentials is safe.
 */
export const OPEN_ASSET_HEADERS: Readonly<Record<string, string>> = {
  "Cross-Origin-Resource-Policy": "cross-origin",
  "Access-Control-Allow-Origin": "*",
};

/**
 * The `_headers` rules that open each path in {@link OPEN_ASSETS}.
 *
 * Cloudflare joins the values of a header that two matching rules set, so
 * each rule first detaches (`! Name`) the `same-origin` value the `/*` rule
 * set before setting its own.
 *
 * @returns The rules, one block per path, ending in a newline.
 */
export function openAssetHeaders(): string {
  const blocks = OPEN_ASSETS.map((path) => {
    const lines = [path];
    for (const [name, value] of Object.entries(OPEN_ASSET_HEADERS)) {
      lines.push(`  ! ${name}`, `  ${name}: ${value}`);
    }
    return lines.join("\n");
  });
  return [
    "# Generated by build.ts from OPEN_ASSETS in cross-origin.ts: the favicons",
    "# and the Open Graph image, which other origins may embed and read.",
    blocks.join("\n\n"),
    "",
  ].join("\n");
}
