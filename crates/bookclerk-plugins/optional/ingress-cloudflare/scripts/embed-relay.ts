/**
 * Writes `src/relay-source.ts`: the relay Worker's emitted modules as text,
 * for the plugin to upload to Cloudflare.
 *
 * `npm run build` runs `tsc`, then this script, then `tsc` again, so
 * `modules/relay-source.js` carries the modules the same build emitted.
 * The relay Worker imports only `relay-core.js` and `protocol.js`, which
 * the plugin loads too, so one source tree serves both ends.
 */

import { readFileSync, writeFileSync } from "node:fs";

/** Modules the relay Worker is made of, main module first. */
const MODULES = ["relay-worker.js", "relay-core.js", "protocol.js"];

const root = new URL("../", import.meta.url);
const entries = MODULES.map((name) => {
  const source = readFileSync(new URL(`modules/${name}`, root), "utf8");
  return `  {\n    name: ${JSON.stringify(name)},\n    source: ${JSON.stringify(source)},\n  },\n`;
});

const out = `// Generated by \`npm run build\` (scripts/embed-relay.ts) from the emitted
// relay modules. Do not edit.

/** One module of the relay Worker, as uploaded to Cloudflare. */
export interface RelayModule {
  /** Module name; the first entry is the Worker's main module. */
  name: string;
  /** The module's JavaScript. */
  source: string;
}

/** The relay Worker's modules, main module first. */
export const RELAY_MODULES: readonly RelayModule[] = [
${entries.join("")}];
`;

writeFileSync(new URL("src/relay-source.ts", root), out);
